CREATE TABLE IF NOT EXISTS usuarios (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(150)  NOT NULL,
    email       VARCHAR(255)  NOT NULL,
    alergias    TEXT,
    senha_hash  VARCHAR(512)  NOT NULL,
    criado_em   TIMESTAMPTZ   NOT NULL DEFAULT now()
);

-- E-mail único sem diferenciar maiúsculas/minúsculas
CREATE UNIQUE INDEX IF NOT EXISTS ux_usuarios_email_lower ON usuarios (lower(email));

CREATE TABLE IF NOT EXISTS sintomas (
    id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id     INTEGER       NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
    tipo           VARCHAR(20)   NOT NULL,
    subtipo        VARCHAR(30),
    descricao      VARCHAR(1000),
    inicio         TIMESTAMPTZ   NOT NULL,
    fim            TIMESTAMPTZ,
    criado_em      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    atualizado_em  TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT ck_sintomas_tipo CHECK (tipo IN (
        'DOR','NAUSEA','FADIGA','VERTIGEM','FALTA_AR',
        'TOSSE','DIARREIA','CONSTIPACAO','COCEIRA','OUTRO'
    )),
    CONSTRAINT ck_sintomas_subtipo CHECK (subtipo IS NULL OR tipo = 'DOR'),
    CONSTRAINT ck_sintomas_periodo CHECK (fim IS NULL OR fim >= inicio)
);

-- Consultas do calendário sempre filtram por usuário + data
CREATE INDEX IF NOT EXISTS ix_sintomas_usuario_inicio ON sintomas (usuario_id, inicio);

-- atualizado_em é atualizado sozinho em qualquer UPDATE
CREATE OR REPLACE FUNCTION set_atualizado_em() RETURNS trigger AS $$
BEGIN
    NEW.atualizado_em := now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_sintomas_atualizado_em ON sintomas;
CREATE TRIGGER trg_sintomas_atualizado_em
    BEFORE UPDATE ON sintomas
    FOR EACH ROW EXECUTE FUNCTION set_atualizado_em();
